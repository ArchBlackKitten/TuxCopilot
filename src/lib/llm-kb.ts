export interface LlmModel {
  tag: string; // ollama pull tag
  family: string;
  params: string;
  sizeGB: number; // download size (Q4/MXFP4)
  ramGB: number; // runtime memory estimate incl. context overhead
  quant: string;
  ctx: string;
  specialties: Specialty[];
  strengths: string;
  limitations: string;
  /** Quality per speciality, 1–10 — models are compared inside a speciality,
   *  never on one overall scale. */
  quality: Partial<Record<Specialty, number>>;
  gpuPreferred: boolean; // benefits strongly from discrete VRAM
  year: number;
  note?: string;
  /** Embedding helpers etc. — useful for RAG but must never be crowned
   *  "best fit" for a task (they cannot chat). */
  auxiliary?: boolean;
}

