export function modelByTag(tag: string): LlmModel | null {
  const t = tag.trim().toLowerCase();
  return MODELS.find((m) => m.tag.toLowerCase() === t) ?? null;
}

/** Match an installed/entered model name to the KB, tolerating quant suffixes
 *  like "llama3.2:3b-instruct-q4_K_M". */
export function matchModel(name: string): LlmModel | null {
  const n = name.trim().toLowerCase();
  const exact = modelByTag(n);
  if (exact) return exact;
  // Try base tag before any quant suffix: "llama3.2:3b-instruct-q4_k_m" → "llama3.2:3b"
  const m = n.match(/^([\w.]+:[\w.]+?)(?:[-_](?:instruct|text|q\d.*|f?p?\d*.*))?$/);
  if (m) {
    const base = MODELS.find((mm) => n.startsWith(mm.tag.toLowerCase()));
    if (base) return base;
  }
  return null;
}
